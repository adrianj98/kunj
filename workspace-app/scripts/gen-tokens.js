#!/usr/bin/env node
// Generates Sources/KunjWorkspaceCore/Design/DesignTokens.swift from
// docs/workspace-app/design/tokens.json. Run from workspace-app/: node scripts/gen-tokens.js
// The output is committed; DesignTokensTests fails when it drifts from the JSON.
const fs = require('fs');
const path = require('path');

const appDir = path.resolve(__dirname, '..');
const src = path.resolve(appDir, '../docs/workspace-app/design/tokens.json');
const dst = path.join(appDir, 'Sources/KunjWorkspaceCore/Design/DesignTokens.swift');
const tokens = JSON.parse(fs.readFileSync(src, 'utf8'));

const px = (v) => {
  const m = /^\s*([0-9.]+)/.exec(String(v));
  if (!m) throw new Error(`not a size: ${v}`);
  return Number(m[1]);
};
const num = (v) => (Number.isInteger(v) ? `${v}.0` : String(v));

const themeNames = Object.keys(tokens.themes);
const keys = Object.keys(tokens.themes[themeNames[0]]);
for (const n of themeNames) {
  const k = Object.keys(tokens.themes[n]);
  if (k.join() !== keys.join()) throw new Error(`theme ${n} has different keys`);
}
for (const k of keys) if (!/^[a-z][A-Za-z0-9]*$/.test(k)) throw new Error(`bad key ${k}`);

const L = tokens.layout;
const [padV, padH] = String(L['sidebar-row-padding']).split(/\s+/).map(px);
const split = String(L['pane-split']).split(/\s+/).map(px);
const T = tokens.type;
const R = tokens.radius;

const lines = [];
lines.push('// Generated by scripts/gen-tokens.js from docs/workspace-app/design/tokens.json; do not edit');
lines.push('');
lines.push('public enum DesignTokens {');
lines.push('    public struct ThemeTokens: Equatable, Sendable {');
lines.push('        public let name: String');
for (const k of keys) lines.push(`        public let ${k}: String`);
lines.push('    }');
lines.push('');
for (const n of themeNames) {
  const t = tokens.themes[n];
  lines.push(`    public static let ${n} = ThemeTokens(`);
  lines.push(`        name: ${JSON.stringify(n)},`);
  keys.forEach((k, i) => lines.push(`        ${k}: ${JSON.stringify(t[k])}${i < keys.length - 1 ? ',' : ''}`));
  lines.push('    )');
  lines.push('');
}
lines.push(`    public static let themes: [ThemeTokens] = [${themeNames.join(', ')}]`);
lines.push('');
lines.push('    public enum Layout {');
lines.push(`        public static let sidebarWidth = ${num(px(L['sidebar-width']))}`);
lines.push(`        public static let headerHeight = ${num(px(L['header-height']))}`);
lines.push(`        public static let tabbarHeight = ${num(px(L['tabbar-height']))}`);
lines.push(`        public static let statusbarHeight = ${num(px(L['statusbar-height']))}`);
lines.push(`        public static let changesFileListWidth = ${num(px(L['changes-file-list-width']))}`);
lines.push(`        public static let sidebarRowPaddingV = ${num(padV)}`);
lines.push(`        public static let sidebarRowPaddingH = ${num(padH)}`);
lines.push(`        public static let paneSplit: (Double, Double) = (${num(split[0])}, ${num(split[1])})`);
lines.push('    }');
lines.push('');
lines.push('    public enum Radius {');
lines.push(`        public static let control = ${num(px(R.control))}`);
lines.push(`        public static let card = ${num(px(R.card))}`);
lines.push(`        public static let window = ${num(px(R.window))}`);
lines.push('    }');
lines.push('');
lines.push('    public enum TypeScale {');
lines.push(`        public static let body = ${num(px(T.body))}`);
lines.push(`        public static let small = ${num(px(T.small))}`);
lines.push(`        public static let caption = ${num(px(T.caption))}`);
lines.push(`        public static let monoTerminal = ${num(px(T['mono-terminal']))}`);
lines.push(`        public static let monoDiff = ${num(px(T['mono-diff']))}`);
lines.push(`        public static let title = ${num(px(T.title))}`);
lines.push('        /// Keyboard hints next to controls (DESIGN.md: mono 10.5px); not in tokens.json');
lines.push('        public static let hint = 10.5');
lines.push('    }');
lines.push('');
lines.push('    /// Font family names of the bundled fonts (Resources/fonts, scripts/fetch-fonts.sh)');
lines.push('    public enum Fonts {');
lines.push('        public static let sans = "Inter"');
lines.push('        public static let mono = "JetBrainsMono"');
lines.push('    }');
lines.push('}');
lines.push('');
lines.push('public typealias ThemeTokens = DesignTokens.ThemeTokens');
lines.push('');

fs.writeFileSync(dst, lines.join('\n'));
console.log(`wrote ${path.relative(appDir, dst)}`);
