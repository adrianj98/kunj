#!/usr/bin/env node
// Writes the Overview window's demo data and test fixture from kunj's own layout
// (dist/lib/agent-overview.js, so `npm run build` in the repository root first):
//   Sources/KunjWorkspace/Demo/DemoPlans.swift               what `--demo --overview` draws
//   Tests/Fixtures/responses/agent_overview_containers.json  what fake-kunj answers
// The agents are the mockup's (docs/workspace-app/design/mockups/overview.html). Run it again
// after a change to the layout or to AgentOverviewJson.
const fs = require('fs');
const path = require('path');
const { buildOverview } = require('../../dist/lib/agent-overview.js');

const steps = items => items.map(([s, subject], i) => ({ id: String(i + 1), subject, status: s === 'd' ? 'completed' : s === 'c' ? 'in_progress' : 'pending' }));
const plan = (session, title, branch, items, extra = {}) => {
  const list = steps(items);
  const current = list.findIndex(s => s.status === 'in_progress');
  return { session, id: null, branch, worktree: `/Users/demo/src/${branch}`, title, running: true, state: 'running', steps: list,
    current: current === -1 ? null : current, markers: [], subagents: [], updatedAt: '2026-11-23T04:46:00.000Z', ...extra };
};
const sub = (id, task, fromStep, toStep, running, items) => ({ id, type: 'general-purpose', task, fromStep, toStep, running, steps: steps(items) });

const repos = [
  { repo: { name: 'kunj', root: '/Users/demo/src/kunj' }, plans: [
    plan('kunj-kunj-feat-agent-overview', 'Agent overview window', 'feat/agent-overview',
      [['d', 'Probe the hooks'], ['d', 'Capture in hooks'], ['d', 'Plan reducer'], ['c', 'agent plan --json'], ['t', 'Events action'], ['t', 'Docs and okf']],
      { subagents: [sub('s1', 'write reducer tests', 2, null, true, [['d', 'Record fixtures'], ['c', 'Unit tests'], ['t', 'Edge cases']])] }),
    plan('kunj-kunj-feat-agent-overview-app', 'Overview window (app)', 'feat/agent-overview-app',
      [['d', 'Layout maths'], ['c', 'Line view'], ['t', 'Row list'], ['t', 'Demo data'], ['t', 'Screenshot check']],
      { parent: { session: 'kunj-kunj-feat-agent-overview', step: 1 } }),
    plan('kunj-kunj-feat-vscode-search', 'Search in VS Code', 'feat/vscode-search',
      [['d', 'Quick pick'], ['d', 'Run kunj search'], ['c', 'Open the result'], ['t', 'Tests']],
      { state: 'waiting', markers: [{ type: 'branch', afterStep: 0, from: 'main', to: 'feat/vscode-search', at: '2026-11-23T04:40:00.000Z' }] }),
    plan('agent', 'Remote terminal hangup', 'fix/remote-pty', [], { container: 'kunj-kunj-fix-remote-pty', worktree: '/workspace' }),
    plan('kunj-kunj-old-idea', 'An agent that ended', 'old-idea', [['d', 'Only step']], { running: false, state: null }),
  ] },
  { repo: { name: 'alertd-core', root: '/Users/demo/src/alertd-core' }, plans: [
    plan('agent', 'Usage rollup endpoint', 'feat/llm-insights',
      [['d', 'Read spend tables'], ['d', 'Add the route'], ['d', 'Tests'], ['d', 'OpenAPI'], ['c', 'Pagination']],
      { state: 'waiting', container: 'alertd-core-feat-llm-insights', worktree: '/workspace' }),
    plan('agent-two', 'Try cursor pagination', 'feat/llm-insights', [['d', 'Cursor param'], ['c', 'Tests']],
      { id: 'two', container: 'alertd-core-feat-llm-insights', worktree: '/workspace', parent: { session: 'agent', step: 3 } }),
    plan('kunj-alertd-core-fix-alert-dedupe', 'Dedupe alert fan-out', 'fix/alert-dedupe',
      [['d', 'Reproduce'], ['d', 'Failing test'], ['c', 'Fix the fan-out'], ['t', 'Run the suite'], ['t', 'Open the PR']],
      { subagents: [sub('s2', 'find fan-out callers', 0, 1, false, [['d', 'Grep callers'], ['d', 'Read queue code']])] }),
  ] },
];

const overviews = repos.map(r => ({ repo: r.repo, ...buildOverview(r.plans), containers: { available: true } }));
const app = path.resolve(__dirname, '..');
fs.writeFileSync(path.join(app, 'Tests/Fixtures/responses/agent_overview_containers.json'), JSON.stringify(overviews[0], null, 2) + '\n');
const swift = `import Foundation
import KunjWorkspaceCore

// Generated by scripts/gen-overview-demo.js from kunj's own layout: do not edit by hand.
/// The Overview mockup's agents (docs/workspace-app/design/mockups/overview.html) for
/// \`--demo --overview\`, as \`kunj agent overview --json\` prints them, one document per repository.
enum DemoPlans {
    static let overviews: [AgentOverviewJson] = {
        (try? JSONDecoder().decode([AgentOverviewJson].self, from: Data(json.utf8))) ?? []
    }()

    private static let json = #"""
${JSON.stringify(overviews)}
"""#
}
`;
fs.writeFileSync(path.join(app, 'Sources/KunjWorkspace/Demo/DemoPlans.swift'), swift);
console.log(overviews.map(o => `${o.repo.name}: ${o.summary}`).join('\n'));
